// Tarjima yordamchisi: {kalit} o'rinbosarlari bilan (ET naqshi)
function PTT(key, vars) {
  let s = (typeof APP !== "undefined" && APP && APP.t && APP.t[key] !== undefined)
    ? APP.t[key] : (PT_TEXTS.uz[key] !== undefined ? PT_TEXTS.uz[key] : "");
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}
