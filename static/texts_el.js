// TEXTS ga qo'shamiz (texts_division.js bilan bir xil usul)
if (typeof TEXTS !== "undefined") {
  for (const lang of ["uz", "ru", "en"]) {
    if (TEXTS[lang]) Object.assign(TEXTS[lang], EL_TEXTS[lang]);
  }
}

// Tarjima yordamchisi — APP.t dan oladi, topilmasa o'zbekcha zaxira (DT bilan bir xil)
function ET(key) {
  if (typeof APP !== "undefined" && APP && APP.t && APP.t[key] !== undefined) return APP.t[key];
  if (EL_TEXTS.uz[key] !== undefined) return EL_TEXTS.uz[key];
  return "";
}
