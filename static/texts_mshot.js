function msErr(e) {
  const code = String((e && e.message) || e || "");
  const map = (APP.t && APP.t.ms_err) || MSHOT_TEXTS.uz.ms_err;
  const k = Object.keys(map).find(x => code === x || code.includes(x));
  return "❌ " + (k ? map[k] : code);
}
